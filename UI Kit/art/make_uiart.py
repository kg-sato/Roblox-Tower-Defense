"""Builds UI Kit/luau/UIArt.luau from art/out/manifest.json (+ art/ids.json once sprites are uploaded).

Run after make_chrome.py (or after dropping new sprites into art/out and listing them in the manifest):
    python "UI Kit/art/make_uiart.py"

ids.json format (written after an approved upload): {"btn_green": "rbxassetid://123", ...}
Until a sprite has an id it is shown from Studio's local content folder (dev preview only):
    %LOCALAPPDATA%\\Roblox\\Versions\\<current>\\content\\textures\\uikit\\<name>.png
Run  python "UI Kit/art/preview_install.py"  to copy the PNGs there.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
manifest = json.load(open(os.path.join(HERE, "out", "manifest.json"), encoding="utf-8"))
extra_path = os.path.join(HERE, "extra_manifest.json")  # written by ingest_art.py
if os.path.exists(extra_path):
    for _name, _m in json.load(open(extra_path, encoding="utf-8")).items():
        if os.path.exists(os.path.join(HERE, "out", _m["file"])):
            manifest[_name] = _m
ids_path = os.path.join(HERE, "ids.json")
ids = json.load(open(ids_path, encoding="utf-8")) if os.path.exists(ids_path) else {}

lines = [
    "--!nocheck",
    "-- GENERATED by UI Kit/art/make_uiart.py from art/out/manifest.json. Do not edit by hand.",
    "-- sprites[name] = { w, h, slice = {left, top, right, bottom} (9-slice insets in source pixels) }",
    "-- ids[name]     = \"rbxassetid://...\" once the sprite has been uploaded (needs the user's OK).",
    "-- Until then, in Studio only, images load from the local content folder (see preview_install.py).",
    "local RunService = game:GetService(\"RunService\")",
    "",
    "local UIArt = {}",
    "UIArt.localRoot = \"rbxasset://textures/uikit_v6/\"",
    "UIArt.useLocal = RunService:IsStudio()",
    "",
    "UIArt.sprites = {",
]
for name in sorted(manifest):
    m = manifest[name]
    sl = ""
    if "slice" in m:
        sl = ", slice = { %d, %d, %d, %d }" % tuple(m["slice"])
    cap = ", cap = %s" % m["cap"] if "cap" in m else ""
    lines.append('\t["%s"] = { w = %d, h = %d%s%s },' % (name, m["w"], m["h"], sl, cap))
lines.append("}")
lines.append("")
lines.append("UIArt.ids = {")
for name in sorted(ids):
    lines.append('\t["%s"] = "%s",' % (name, ids[name]))
lines.append("}")
lines.append("")
lines += [
    "-- the image to show for a sprite, or nil if it cannot be shown on this machine",
    "function UIArt.image(name)",
    "\tif UIArt.ids[name] then",
    "\t\treturn UIArt.ids[name]",
    "\tend",
    "\tif UIArt.useLocal and UIArt.sprites[name] then",
    "\t\treturn UIArt.localRoot .. name .. \".png\"",
    "\tend",
    "\treturn nil",
    "end",
    "",
    "function UIArt.has(name)",
    "\treturn UIArt.sprites[name] ~= nil and UIArt.image(name) ~= nil",
    "end",
    "",
    "return UIArt",
    "",
]
out = os.path.join(ROOT, "luau", "UIArt.luau")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", out, "with", len(manifest), "sprites and", len(ids), "ids")





