"""Writes K3-TEST-PROMPT.md: a Kimi K3 test pack that uses the same Sols style and item descriptions as the ComfyUI icons,
so the two outputs can be compared item by item. Test images go to k3_test/inbox/ (never to art/inbox/), so they cannot
replace real sprites by accident.

    python "UI Kit/art/k3_test/make_k3_test.py"

Then paste the blocks from K3-TEST-PROMPT.md into Kimi K3 and run check_k3_test.py on the inbox folder.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.dirname(HERE)
sys.path.insert(0, ART)
import comfy_generate as cg  # noqa: E402  (its main() is guarded, so importing it is safe)
from sols_descriptions import SOLS  # noqa: E402

PET = ("a small star drake, one creature, whole body visible, legs and claws visible, curved gold horns, "
       "two folded leather wings, a row of spikes along the back, a long tail ending in a glowing star, "
       "a cyan gem in the chest")
PET_COMPOSITION = ("three-quarter view, whole body fully inside the frame, even lighting, no cast shadow, "
                   "one single creature only, standing")

BATCHES = [
    ("Batch 1 (icons)", [(n, SOLS[n]) for n in ["icon_shop", "icon_index", "icon_pickaxe", "icon_dragon"]]),
    ("Batch 2 (icon and pet)", [("icon_trade", SOLS["icon_trade"]), ("pet_star_drake", PET)]),
]

MASTER = """You are the art generator for a dark-fantasy Roblox game UI. I will give you a list of items. For EACH item
make ONE image, in the style below. Do not invent extra items.

Style (identical for every image): {style}

Background: one flat solid colour, exactly #FF00FF (pure magenta), covering the whole canvas, with no gradient, no
vignette, no floor. The subject must not contain magenta. No frame or border around the picture. Square, 1024 x 1024 PNG.

File names: save each image with the exact file name I give, into this folder:
C:\\Users\\kgsat\\Documents\\Roblox\\UI Kit\\art\\k3_test\\inbox\\
If you cannot save files there yourself, say so and I will download them and move them.

After each batch, list the file names you produced and anything you were unsure about."""


def item_prompt(desc, composition):
    # same order as comfy_generate.py: background first, then the item, then composition, then style
    return "%s. %s, %s, %s" % (cg.BG_PREFIX, desc, composition, cg.STYLE_SOLS)


def main():
    lines = [
        "# Kimi K3 test pack",
        "",
        "Generated by `make_k3_test.py` from the same Sols style and descriptions as the ComfyUI icons",
        "(`comfy_generate.py`, `sols_descriptions.py`). Do not edit by hand; edit the script and rerun it.",
        "",
        "How to run it:",
        "1. Open Kimi K3 in a new chat. Paste **Paste 1** once.",
        "2. Paste **Paste 2** (batch 1). Kimi saves the files into `k3_test/inbox/`.",
        "3. Paste **Paste 3** (batch 2) in the same chat.",
        "4. Run: `python \"UI Kit/art/k3_test/check_k3_test.py\"`. It checks the background, the fill and the outline colour rules.",
        "5. Compare each K3 image with the ComfyUI one of the same name in `UI Kit/art/comfy_out/` (same description).",
        "   Run the checker on that folder too, for a baseline: `python \"UI Kit/art/k3_test/check_k3_test.py\" \"UI Kit/art/comfy_out\"`.",
        "",
        "Scoring is by eye as well: style match, one object, no text, upright, a readable silhouette at 64 px.",
        "",
        "## Paste 1 (master prompt)",
        "",
        "```text",
        MASTER.format(style=cg.STYLE_SOLS),
        "```",
        "",
    ]
    paste = 2
    for title, items in BATCHES:
        lines += ["## Paste %d: %s" % (paste, title), "", "```text"]
        for name, desc in items:
            composition = PET_COMPOSITION if name.startswith("pet_") else cg.COMPOSITION
            lines.append("file: k3test_%s.png" % name)
            lines.append("draw: %s" % item_prompt(desc, composition))
            lines.append("")
        lines += ["```", ""]
        paste += 1
    out = os.path.join(HERE, "K3-TEST-PROMPT.md")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
