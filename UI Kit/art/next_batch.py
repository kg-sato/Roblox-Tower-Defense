"""Writes the next Kimi batch automatically: every icon the screens use that has no real sprite yet.

    python "UI Kit/art/next_batch.py"

Scans UI Kit/luau/UIScreens.luau for `icon = "..."` values and for emoji passed as icons, compares them with the sprites
in UIArt.luau, and writes art/briefs/NEXT-BATCH.md in the same format as BATCH-1-ICONS.md (file name + what to draw).
Descriptions come from DESCRIPTIONS below; add a line there when a new icon name appears. Names without a description
are listed as "needs a description". Run it after adding or changing screens; paste the result to Kimi.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
screens = open(os.path.join(ROOT, "luau", "UIScreens.luau"), encoding="utf-8").read()
uiart = open(os.path.join(ROOT, "luau", "UIArt.luau"), encoding="utf-8").read()
have = set(re.findall(r'\["([a-z0-9_]+)"\] = \{ w =', uiart))

# emoji used in screens -> the sprite name we want for it
EMOJI = {
    "🛒": "icon_shop", "📖": "icon_index", "🔁": "icon_trade", "🔄": "icon_rebirth", "🥚": "icon_egg", "🐾": "icon_paw",
    "⛏️": "icon_pickaxe", "👟": "icon_shoe", "🎁": "icon_gift", "🐲": "icon_dragon", "🐉": "icon_dragon", "🧄": "icon_garlic",
    "🍎": "icon_apple", "⏱": "icon_stopwatch", "🍬": "icon_candy", "🔧": "icon_wrench", "🧈": "icon_gold_bar", "🍇": "icon_grapes",
    "🍉": "icon_melon", "🙂": "icon_player", "🏁": "icon_flag",
}
DESCRIPTIONS = {
    "icon_shop": "a small shopping cart seen from the front-left, green handle, silver basket, two round wheels",
    "icon_index": "a thick closed storybook, blue cover, gold corner caps, cream pages visible, gold star on the cover",
    "icon_trade": "two chunky arrows chasing each other in a loop (one orange, one blue), swap symbol",
    "icon_rebirth": "a circular refresh arrow with a small glowing star in the middle, blue and white",
    "icon_pickaxe": "a cartoon pickaxe, grey steel head with a bright highlight, wooden handle, tilted 45 degrees",
    "icon_shoe": "a red and white running shoe with a lightning bolt on the side, glossy, 3/4 view",
    "icon_dragon": "a cute green baby dragon head with small horns and a friendly grin, side view",
    "icon_garlic": "a garlic bulb, off-white with purple stripes and a small stem",
    "icon_apple": "a shiny red apple with one green leaf",
    "icon_stopwatch": "a silver stopwatch with a white face, red hand and a small top button",
    "icon_candy": "a wrapped candy, pink and white swirl, twisted wrapper ends",
    "icon_wrench": "a chunky grey wrench with a bright highlight",
    "icon_gold_bar": "a stack of two shiny gold bars",
    "icon_grapes": "a bunch of purple grapes with a green leaf",
    "icon_melon": "a slice of watermelon with black seeds, red flesh, green rind",
    "icon_player": "a round smiling yellow face (player marker), thick outline",
    "icon_flag": "a chequered racing flag on a short grey pole",
    "icon_sword": "a short sword tilted 45 degrees, silver blade, gold guard, blue handle",
    "icon_shield": "a round-top shield, blue with a gold rim and a white star in the middle",
    "icon_skull": "a friendly cartoon skull (enemy wave marker), off-white, big eye sockets, purple tint",
    "icon_rod": "a wooden fishing rod tilted 45 degrees, orange-brown glossy wood, silver reel, thin line with a small red and white bobber",
    "icon_bag": "a chunky white backpack-style item bag with a small handle on top and a front pocket, light grey shading",
    "icon_clover": "a four-leaf clover, bright green leaves with white highlights, short stem",
    "icon_hook": "a shiny silver fishing hook with a small loop at the top, curved bottom with a barb",
    "icon_bell": "a golden notification bell with a small clapper, glossy",
    "icon_fish": "a cute orange cartoon fish, side view, big eye, small fins",
    "icon_wave": "a stylised ocean wave curling to the right, bright blue with white foam",
}

wanted = {}
for m in re.finditer(r'icon = "([^"]+)"', screens):
    v = m.group(1)
    wanted[EMOJI.get(v, v)] = v
for m in re.finditer(r'text = "([^"A-Za-z0-9 ]+)"', screens):
    v = m.group(1)
    if v in EMOJI:
        wanted[EMOJI[v]] = v

missing = sorted(n for n in wanted if n.startswith("icon_") and n not in have)
lines = ["# NEXT BATCH (auto-generated by next_batch.py)", "",
         "Icons that screens use but that have no real sprite yet. Paste to Kimi after the master prompt, 4 to 6 per request.", "",
         "| File | Draw |", "|---|---|"]
for n in missing:
    lines.append("| `%s.png` | %s |" % (n, DESCRIPTIONS.get(n, "NEEDS A DESCRIPTION: add it to DESCRIPTIONS in next_batch.py")))
if not missing:
    lines.append("| (nothing missing) | every icon used by the screens has a sprite |")
out = os.path.join(HERE, "briefs", "NEXT-BATCH.md")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(missing), "icon(s) missing ->", out)
for n in missing:
    print(" ", n)
