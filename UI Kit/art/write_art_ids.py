"""Turns UI Kit/art/upload_1028/ids.txt (name assetId per line, from upload_asset.py) into Studio_Export/ArtIds.luau and
fills the ID_* placeholders in Studio_Export/LoadingScreen.luau (which runs too early to require ArtIds)."""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ids = {}
for line in open(os.path.join(ROOT, "UI Kit", "art", "upload_1028", "ids.txt"), encoding="utf-8"):
    p = line.split()
    if len(p) == 2:
        ids[p[0]] = "rbxassetid://" + p[1]
key = {"title": "title", "lamp": "lamp", "clock": "clock", "ring": "clock_ring", "gear": "gear", "eye": "eye", "tree": "tree",
       "frame": "popup_frame2", "track_h": "track_h", "track_v": "track_v", "lantern_frame": "lantern_frame", "lantern_glass": "lantern_glass", "coin": "coin", "gem": "gem", "road_lane": "road_lane", "road_veil": "road_veil", "road_stars": "road_stars", "tree_clean": "tree_clean", "chain_h": "chain_h", "chain_v": "chain_v", "script": "script_tile", "hex": "node_hex", "glow": "node_glow"}
out = ["-- ArtIds (ReplicatedStorage ModuleScript, 2026-10-28): uploaded image ids for the start menu, skill tree and grove.",
       "-- Generated by UI Kit/art/write_art_ids.py from upload_1028/ids.txt; sources in UI Kit/art (make_menu_art.py,",
       "-- make_tree_art.py, render_title.py). Also listed in VFX/ASSETS.md.", "return {"]
for k, f in key.items():
    out.append('\t%s = "%s",' % (k, ids.get(f, "")))
out.append("\ticons = {")
for f, v in sorted(ids.items()):
    if f.startswith("icon_"):
        out.append('\t\t%s = "%s",' % (f[5:], v))
out += ["\t},", "}", ""]
open(os.path.join(ROOT, "Studio_Export", "ArtIds.luau"), "w", encoding="utf-8", newline="").write("\n".join(out))
ls = os.path.join(ROOT, "Studio_Export", "LoadingScreen.luau")
s = open(ls, encoding="utf-8").read()
for ph, f in {"ID_TITLE": "title", "ID_CLOCK": "clock", "ID_GEAR": "gear", "ID_TREE": "tree", "ID_EYE": "eye", "ID_GLOW": "node_glow", "ID_RING": "clock_ring", "ID_SOCKET": "eye_socket", "ID_IRIS": "eye_iris"}.items():
    s = s.replace("rbxassetid://" + ph, ids[f])
open(ls, "w", encoding="utf-8", newline="").write(s)
print(len(ids), "ids; placeholders left:", re.findall(r"ID_[A-Z]+", s))
