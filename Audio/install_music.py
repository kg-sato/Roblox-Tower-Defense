"""Copies Audio/Music/game/*.ogg into Studio's local content folder (dev preview only) and writes VFX/MusicCatalog.luau
from Audio/Music/music_analysis.json (run analyze_music.py on Music/game first).

    python Audio/install_music.py          install + write catalog
    python Audio/install_music.py --remove

Studio loads rbxasset://sounds/music/<name>.ogg from <Studio version>\\content\\sounds\\music\\. A published game needs the files
uploaded to Roblox (the owner's account, needs the owner's OK) and the catalog switched to asset ids.
"""
import glob
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "Music", "game")
versions = os.path.join(os.environ["LOCALAPPDATA"], "Roblox", "Versions")
targets = [os.path.join(os.path.dirname(e), "content", "sounds", "music") for e in glob.glob(os.path.join(versions, "version-*", "RobloxStudioBeta.exe"))]
if "--remove" in sys.argv:
    for t in targets:
        shutil.rmtree(t, ignore_errors=True)
        print("removed", t)
    sys.exit()
for t in targets:
    os.makedirs(t, exist_ok=True)
    for f in glob.glob(os.path.join(GAME, "*.ogg")):
        shutil.copy2(f, t)
    print("installed", len(os.listdir(t)), "tracks to", t)

ana = json.load(open(os.path.join(HERE, "Music", "music_analysis.json")))
# vol: per-track trim on top of the common loudness; loop: use Looped = true; credit: shown in the credits screen
META = {
    "shinsei": (0.55, False, "Gichco - Shinsei"),
    "chill_lofi": (0.55, False, "omfgdude - Chill lofi inspired"),
    "rising_moon": (0.55, False, "RandomMind - Fantasy: Rising Moon"),
    "artifact_room": (0.55, True, "Fupi - Artifact Room"),
    "iremos_forest": (0.5, True, "beardalaxy - Iremos Forest Theme Loop"),
}
lines = ["--!nocheck", "-- GENERATED by Audio/install_music.py from Audio/Music/music_analysis.json. Do not edit by hand.", "-- dur = measured seconds (the engine audit checks Sound.TimeLength), vol = trim, loop = seamless enough to loop.", "return {"]
for key in sorted(META):
    a = ana[key + ".ogg"]
    vol, loop, credit = META[key]
    lines.append('\t%s = { dur = %.2f, vol = %.2f, loop = %s, credit = "%s", rms = %.1f, peak = %.1f },' % (key, a["dur"], vol, str(loop).lower(), credit, a["rms_db"], a["peak_db"]))
lines.append("}")
open(os.path.join(HERE, "..", "VFX", "MusicCatalog.luau"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote VFX/MusicCatalog.luau")
