"""Writes VFX/SoundCatalog.luau from analysis.json (expected duration per sound) plus the mix settings below.
    python VFX/sfx/gen_catalog.py
Run analyze_sfx.py first. The engine audit compares Sound.TimeLength with these durations."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(HERE, "analysis.json")))
# vol: mix level 0..1; pri: 1 UI, 2 effect, 3 hero (UI is dropped first when too many sounds play at once); jit: pitch jitter
MIX = {
    "ui_click": (0.45, 1, 0.04), "combo": (0.55, 1, 0.03), "ring": (0.5, 1, 0.03), "milestone": (0.7, 2, 0.0), "spotlight": (0.5, 1, 0.02),
    "menu_open": (0.55, 1, 0.02), "menu_close": (0.5, 1, 0.02), "discovery": (0.65, 2, 0.0),
    "load_start": (0.5, 2, 0.0), "load_synced": (0.6, 2, 0.0), "load_resolve": (0.6, 2, 0.0),
    "common": (0.6, 2, 0.03), "rare": (0.7, 2, 0.02), "epic": (0.8, 2, 0.0), "anticipation": (0.6, 3, 0.0),
    "legendary_gather": (0.7, 3, 0.0), "legendary_burst": (0.95, 3, 0.0), "ink": (0.8, 3, 0.0), "vortex": (0.8, 3, 0.0),
    "merge_1": (0.60, 2, 0.02), "merge_2": (0.62, 2, 0.02), "merge_3": (0.66, 2, 0.02), "merge_4": (0.70, 2, 0.0), "merge_5": (0.76, 2, 0.0),
    "merge_6": (0.82, 3, 0.0), "merge_7": (0.88, 3, 0.0), "merge_8": (1.0, 3, 0.0),
    "summon": (0.5, 1, 0.04), "surge": (0.7, 2, 0.0), "echo": (0.45, 1, 0.03), "bank": (0.45, 1, 0.03), "charge_ready": (0.4, 1, 0.0),
    "merge_fail": (0.5, 1, 0.03), "wish_pull": (0.7, 3, 0.0),
    "ultimate_summon": (0.75, 3, 0.0), "ultimate_sword": (0.7, 3, 0.0), "ultimate_fall": (0.8, 3, 0.0), "ultimate_impact": (1.0, 3, 0.0),
}
lines = ["--!nocheck", "-- GENERATED by VFX/sfx/gen_catalog.py from analysis.json. Do not edit by hand.",
         "-- dur = measured length in seconds (the engine audit checks Sound.TimeLength against it), vol = mix level,", "-- pri = priority (1 UI dropped first), jit = random pitch jitter.", "return {"]
for name in sorted(data):
    v, pri, jit = MIX[name]
    lines.append('\t%s = { dur = %.3f, vol = %.2f, pri = %d, jit = %.2f },' % (name, data[name]["dur"], v, pri, jit))
lines.append("}")
open(os.path.join(HERE, "..", "SoundCatalog.luau"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote SoundCatalog.luau with", len(data), "sounds")
