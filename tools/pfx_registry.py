"""Generate VFX/ParticleFXRegistry.luau from VFX/flipbooks/particlefx_catalog.json and Overnight/asset_ids.json (T29).
  python -I tools/pfx_registry.py
Each effect gets: uploaded asset id (or nil), lifetime, loop, a use class and a size in studs. Duplicate sheets
(catalog "identical_files", the *_v1 names) borrow the id of their twin. Size by use follows the ParticleFX guide in
Roblox Dev/Research/VFX and Animation/ParticleFX Studio and Flipbook VFX.md (hits 6-8 studs, ultimates 15-25, placement
about twice the tower width, rings = diameter, set per call)."""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
cat = json.loads((ROOT / "VFX/flipbooks/particlefx_catalog.json").read_text(encoding="utf-8"))
ids_path = ROOT / "Overnight/asset_ids.json"
ids = json.loads(ids_path.read_text(encoding="utf-8")) if ids_path.exists() else {}
alias = {a: b for a, b in cat["identical_files"]}

RULES = [
    ("ui", ["rarity-frames", "notification", "new-item", "tap-glitter", "achievement", "claim", "cooldown", "quest", "badge"]),
    ("ring", ["splash", "range", "ring"]),
    ("status", ["slowed", "regeneration", "aura", "burn", "poison", "freeze", "shield", "buff", "stun", "heal"]),
    ("ultimate", ["orbital", "reaper", "whirlwind", "umbral", "rebirth", "wings", "meteor", "nova", "storm"]),
    ("reveal", ["egg", "hatch", "loot", "summon"]),
    ("defeat", ["coin", "defeat", "death"]),
    ("placement", ["placement", "upgrade", "pad", "respawn", "spawn"]),
]
SIZE = {"hit": 7, "placement": 8, "defeat": 6, "ring": 14, "status": 6, "ultimate": 20, "reveal": 12, "ui": 0}


def use_of(name):
    for use, keys in RULES:
        if any(k in name.lower() for k in keys):
            return use
    return "hit"


lines = ["--!nocheck", "-- Generated by tools/pfx_registry.py from VFX/flipbooks/particlefx_catalog.json and Overnight/asset_ids.json.",
         "-- Do not edit by hand. use: hit / placement / defeat / ring / status / ultimate / reveal / ui; size in studs.", "return {"]
with_id = 0
for name, e in sorted(cat["effects"].items()):
    twin = alias.get(name)
    iid = ids.get(name) or (ids.get(twin) if twin else None)
    with_id += bool(iid)
    use = use_of(name)
    r, g, b = e.get("mean_rgb", [255, 255, 255])
    extra = f', alias = "{twin}"' if twin else ""
    lines.append(f'\t["{name}"] = {{ id = {iid if iid else "nil"}, lifetime = {e["lifetime"]}, loop = {"true" if e["kind"] == "loop" else "false"}, '
                 f'use = "{use}", size = {SIZE[use]}, tint = {{ {r}, {g}, {b} }}{extra} }},')
lines.append("}")
(ROOT / "VFX/ParticleFXRegistry.luau").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(cat["effects"]), "effects,", with_id, "with an asset id;", dict(Counter(use_of(n) for n in cat["effects"])))
