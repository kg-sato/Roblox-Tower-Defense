"""Generate Studio_Export/StageCaptions.luau from Roblox Dev/Lore/Story/Stage Captions.md (the 40 bracketed captions).
Run: python tools/gen_stage_captions.py. The generated module is installed as ReplicatedStorage.Shared.StageCaptions."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
rows = re.findall(r"^\| \d+ \| (\d+) \| ([a-z ]+) \| (\[ [^\]]+ \]) \|", (ROOT / "Roblox Dev" / "Lore" / "Story" / "Stage Captions.md").read_text(encoding="utf-8"), re.M)
d = {}
for st, slot, cap in rows:
    d.setdefault(int(st), {})[slot.strip().replace(" ", "_")] = cap
lines = [
    "--!strict",
    "-- GENERATED by tools/gen_stage_captions.py from Roblox Dev/Lore/Story/Stage Captions.md. Do not edit by hand.",
    "-- stage -> slot -> caption. Slots: intro, boss_warning, boss_defeated, set_clear.",
    "return {",
]
for st in sorted(d):
    lines.append("\t[%d] = { %s }," % (st, ", ".join('%s = "%s"' % (k, v) for k, v in d[st].items())))
lines.append("}")
(ROOT / "Studio_Export" / "StageCaptions.luau").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(rows), "captions")
