"""Generate Studio_Export/Familiars.luau (T101) from the lore files and voice lines, so the Luau data can never drift from the notes.
Reads Roblox Dev/Lore/Familiars/<Name>.md (name, epithet, faction, element, rarity, role verb, role text, home set, identity colour, merge tier features)
and Roblox Dev/Lore/voice_lines.json. Writes the ModuleScript installed in Studio as ReplicatedStorage.Shared.Familiars.
charId links a familiar to its folder in ReplicatedStorage.Characters (T102: all 16 have one; Gargoyle is Boulder, Moth-Lantern is Zap, Mirror Chorister is VoltFox).
Run with any Python 3: python tools/gen_familiars_luau.py"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
LORE = ROOT / "Roblox Dev" / "Lore"
CHAR = {"Ember": "Ember", "Frostling": "Frostling", "StarDrake": "StarDrake", "Gargoyle": "Boulder", "MirrorChorister": "VoltFox", "MothLantern": "Zap",
        "BrassHound": "BrassHound", "Sentinel": "Sentinel", "Ward": "Ward", "Archivist": "Archivist", "Mourner": "Mourner", "GreyVeilWraith": "GreyVeilWraith",
        "CantorVesper": "CantorVesper", "DameOrrery": "DameOrrery", "TheLamplighter": "TheLamplighter", "VeilWalker": "VeilWalker"}
ORDER = ["Ember", "MothLantern", "BrassHound", "Sentinel", "Frostling", "Gargoyle", "Ward", "Archivist", "Mourner", "MirrorChorister", "StarDrake", "GreyVeilWraith", "CantorVesper", "DameOrrery", "TheLamplighter", "VeilWalker"]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def snake(s):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", s).lower()


voice = json.loads((LORE / "voice_lines.json").read_text(encoding="utf-8"))
out = ["--!strict", "-- Familiar data (T101). GENERATED by tools/gen_familiars_luau.py from Roblox Dev/Lore/Familiars/*.md and voice_lines.json: edit the notes, not this file.",
       "-- Installed as ReplicatedStorage.Shared.Familiars. Read by Shared.Config (Config.FAMILIARS and the role, faction, loreId fields of Config.PETS).",
       "-- charId is the folder in ReplicatedStorage.Characters that holds this familiar (T102: all 16 have one).", "",
       "export type Voice = { tone: { string }, summon: string, attack: string, victory: string }",
       "export type Familiar = { id: string, name: string, epithet: string, rarity: string, role: string, roleText: string, faction: string, element: string,",
       "\thome: string, loreId: string, color: Color3, charId: string?, tier2: string, tier3: string, voice: Voice }", "",
       "local Familiars = {}", "", "Familiars.list = {"]
for n in ORDER:
    t = (LORE / "Familiars" / f"{n}.md").read_text(encoding="utf-8")
    ne = re.search(r"\*\*Name and epithet:\*\* (.+?)\.\n", t).group(1)
    name, epithet = [x.strip() for x in ne.split(",", 1)]
    fe = re.search(r"\*\*Faction and element:\*\* (.+?)\. \*\*Rarity:\*\* (\w+)", t)
    faction, element = [x.strip() for x in fe.group(1).split(";", 1)]
    rr = re.search(r"\*\*Role \(one verb\):\*\* (\w+) \((.+?)\)\. \*\*Home set:\*\* (.+?)\.", t)
    col = re.search(r"\*\*Identity colour.*?`#([0-9A-Fa-f]{6})`", t).group(1)
    mt = re.search(r"Merge tiers \(T100, final\): tier 2 adds (.+?) \(.+?\); tier 3 adds (.+?) \(", t)
    v = voice[n]
    r, g, b = (int(col[i:i + 2], 16) for i in (0, 2, 4))
    ch = q(CHAR[n]) if n in CHAR else "nil"
    out.append(f"\t{{ id = {q(n)}, name = {q(name)}, epithet = {q(epithet)}, rarity = {q(fe.group(2))}, role = {q(rr.group(1))}, roleText = {q(rr.group(2))},")
    out.append(f"\t\tfaction = {q(faction)}, element = {q(element)}, home = {q(rr.group(3))}, loreId = {q('lore_' + snake(n))}, color = Color3.fromRGB({r}, {g}, {b}), charId = {ch},")
    out.append(f"\t\ttier2 = {q(mt.group(1))}, tier3 = {q(mt.group(2))},")
    out.append(f"\t\tvoice = {{ tone = {{ {', '.join(q(x) for x in v['tone'])} }}, summon = {q(v['summon'])}, attack = {q(v['attack'])}, victory = {q(v['victory'])} }} }},")
out += ["}", "", "Familiars.byId = {} :: { [string]: Familiar }", "Familiars.order = {} :: { string }",
        "for _, f in Familiars.list do", "\tFamiliars.byId[f.id] = f", "\ttable.insert(Familiars.order, f.id)", "end", "",
        "-- the familiar behind a character folder id (nil for characters that are not in the new cast, such as Sprout)",
        "function Familiars.forChar(charId: string): Familiar?", "\tfor _, f in Familiars.list do", "\t\tif f.charId == charId then", "\t\t\treturn f", "\t\tend", "\tend", "\treturn nil", "end", "",
        "return Familiars", ""]
(ROOT / "Studio_Export" / "Familiars.luau").write_text("\n".join(out), encoding="utf-8")
print("wrote Studio_Export/Familiars.luau,", len(ORDER), "familiars")
